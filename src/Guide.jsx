import { useState } from 'react';
import { ArrowUpRight, Compass, Lightbulb, LoaderCircle, Sparkles } from 'lucide-react';

const starterQuestions = [
  'How do I price my products?',
  'What should I track every day?',
  'How can I attract my first customers?',
];

const Guide = () => {
  const [question, setQuestion] = useState('');
  const [reply, setReply] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const askAI = async (prompt = question) => {
    if (!prompt.trim()) {
      setError('Write a question or choose one of the suggestions.');
      return;
    }
    setQuestion(prompt);
    setError('');
    setLoading(true);
    setReply('');
    try {
      const response = await fetch('/.netlify/functions/openai', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          messages: [{
            role: 'user',
            content: `You are a supportive, practical startup mentor for a small-business owner. Answer clearly in a few short paragraphs, with concrete next steps. Question: ${prompt}`,
          }],
        }),
      });
      const data = await response.json();
      if (!response.ok || !data.result) throw new Error(data.error || 'Could not get a response.');
      setReply(data.result);
    } catch (requestError) {
      setError(requestError.message || 'Chat failed. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="subpage">
      <section className="welcome-row">
        <div>
          <p className="eyebrow"><span className="eyebrow-dot" /> YOUR NEXT CHAPTER</p>
          <h1>Every great business starts <span>with a question.</span></h1>
          <p className="welcome-copy">Get a little direction for the idea you’re working on right now.</p>
        </div>
      </section>
      <section className="guide-layout">
        <article className="panel guide-panel">
          <span className="large-feature-icon guide-feature-icon"><Compass size={23} /></span>
          <p className="panel-kicker">STARTUP GUIDE</p>
          <h2>What would you like help with?</h2>
          <p className="guide-description">Ask a practical question about starting, running, or growing your business.</p>
          <form className="guide-form" onSubmit={(event) => { event.preventDefault(); askAI(); }}>
            <label htmlFor="guide-question" className="visually-hidden">Your question</label>
            <textarea id="guide-question" value={question} onChange={(event) => setQuestion(event.target.value)} placeholder="For example: How do I work out my profit margin?" maxLength={500} rows={4} />
            <div className="guide-form-bottom"><span>{question.length}/500</span><button type="submit" className="primary-button" disabled={loading}>{loading ? <><LoaderCircle className="spin-icon" size={16} /> Thinking…</> : <>Ask your question <ArrowUpRight size={16} /></>}</button></div>
          </form>
          {error && <p className="notice" role="status">{error}</p>}
          {reply && <div className="guide-answer"><div className="ai-summary-title"><Sparkles size={17} /><h3>Your next step</h3></div><p>{reply}</p></div>}
        </article>
        <aside className="guide-aside">
          <div className="guide-aside-heading"><span><Lightbulb size={17} /></span><div><p className="panel-kicker">NEED A START?</p><h3>Try one of these</h3></div></div>
          <div className="question-suggestions">
            {starterQuestions.map((suggestion) => <button key={suggestion} type="button" onClick={() => askAI(suggestion)} disabled={loading}><span>{suggestion}</span><ArrowUpRight size={15} /></button>)}
          </div>
          <p className="guide-privacy">Your answers are generated by AI and are intended as general guidance, not professional financial advice.</p>
        </aside>
      </section>
    </div>
  );
};

export default Guide;
